# ---------------------------------------------------------------- frontmatter


def parse_scalar(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] == '"':
        try:
            loaded = json.loads(value)
            return loaded if isinstance(loaded, str) else value[1:-1]
        except ValueError:
            return value[1:-1]
    if len(value) >= 2 and value[0] == value[-1] == "'":
        return value[1:-1].replace("''", "'")
    return value


def split_inline_list(text: str) -> list[str]:
    items: list[str] = []
    buf: list[str] = []
    quote = ""
    for ch in text:
        if quote:
            buf.append(ch)
            if ch == quote:
                quote = ""
        elif ch in "\"'":
            quote = ch
            buf.append(ch)
        elif ch == ",":
            items.append("".join(buf))
            buf = []
        else:
            buf.append(ch)
    items.append("".join(buf))
    return [parse_scalar(item) for item in items if item.strip()]


def parse_frontmatter(text: str) -> tuple[dict[str, Any] | None, str, int, list[str]]:
    """Return (meta, body, body_start_line_index, errors) for a small YAML subset."""
    lines = text.splitlines(keepends=True)
    if not lines or lines[0].rstrip("\r\n") != "---":
        return None, text, 0, []
    end = next(
        (i for i in range(1, len(lines)) if lines[i].rstrip("\r\n") == "---"), -1
    )
    if end < 0:
        return None, text, 0, ["frontmatter has no closing '---' line"]
    meta: dict[str, Any] = {}
    errors: list[str] = []
    key: str | None = None
    for number, raw in enumerate(lines[1:end], start=2):
        line = raw.rstrip("\r\n")
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        item = re.match(r"^\s*-\s+(.*)$", line)
        if item and key is not None and isinstance(meta.get(key), list):
            meta[key].append(parse_scalar(item.group(1)))
            continue
        pair = re.match(r"^([A-Za-z_][\w-]*):(?:\s+(.*))?$", line)
        if not pair:
            errors.append(f"line {number}: unsupported YAML: {line.strip()}")
            key = None
            continue
        key, value = pair.group(1), (pair.group(2) or "").strip()
        if key in meta:
            errors.append(f"line {number}: duplicate key '{key}'")
        if value == "":
            meta[key] = []
        elif value.startswith("["):
            if not value.endswith("]"):
                errors.append(f"line {number}: inline list must end with ']'")
            meta[key] = split_inline_list(value[1:-1].strip())
        else:
            meta[key] = parse_scalar(value)
    return meta, "".join(lines[end + 1 :]), end + 1, errors


def format_scalar(value: str) -> str:
    if (
        value == ""
        or value != value.strip()
        or value[0] in "-?"
        or re.search(r"[:#\[\]{},\"'&*!|>%@`]", value)
    ):
        return json.dumps(value, ensure_ascii=False)
    return value


def dump_frontmatter(meta: dict[str, str | list[str]]) -> str:
    lines = ["---"]
    for key, value in meta.items():
        if isinstance(value, list):
            lines.append(f"{key}: [{', '.join(format_scalar(v) for v in value)}]")
        else:
            lines.append(f"{key}: {format_scalar(value)}")
    lines.append("---")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- wiki model


@dataclass
class Page:
    path: Path
    rel: str
    meta: dict[str, Any] | None
    body: str
    text: str
    body_line: int
    errors: list[str] = field(default_factory=list)

    def get(self, key: str) -> str:
        value = (self.meta or {}).get(key)
        return value if isinstance(value, str) else ""

    def get_list(self, key: str) -> list[str]:
        value = (self.meta or {}).get(key)
        if isinstance(value, list):
            return [str(v) for v in value if str(v).strip()]
        if isinstance(value, str) and value.strip():
            return [value]
        return []

    @property
    def directory(self) -> str:
        parent = Path(self.rel).parent.as_posix()
        return "" if parent == "." else parent

    @property
    def title(self) -> str:
        return self.get("title") or Path(self.rel).stem


class Wiki:
    def __init__(self, root: Path) -> None:
        self.root = root
        self.raw = root / "raw"
        self.wiki = root / "wiki"
        self.log = self.wiki / "log.md"
        self.schema = root / "AGENTS.md"

    def require(self) -> None:
        if not self.wiki.is_dir():
            raise WikiError(
                "not-initialized",
                f"No wiki at {self.root}. Run: llm_wiki.py init --root {self.root}",
            )

    def extra_kinds(self) -> list[str]:
        if not self.schema.is_file():
            return []
        kinds: list[str] = []
        for match in KINDS_MARKER_RE.finditer(self.schema.read_text(encoding="utf-8")):
            for kind in re.split(r"[,\s]+", match.group(1)):
                if kind and kind not in kinds and kind not in GENERIC_KINDS:
                    kinds.append(kind)
        return kinds

    def kinds(self) -> list[str]:
        return list(GENERIC_KINDS) + self.extra_kinds()

    def is_page_file(self, path: Path) -> bool:
        rel = path.relative_to(self.wiki)
        return (
            path.suffix == ".md"
            and path.name != "index.md"
            and path != self.log
            and not any(part.startswith(".") for part in rel.parts)
        )

    def pages(self) -> list[Page]:
        pages: list[Page] = []
        if not self.wiki.is_dir():
            return pages
        for path in sorted(self.wiki.rglob("*.md")):
            if path.is_file() and self.is_page_file(path):
                pages.append(load_page(self, path))
        return pages

    def dirs(self) -> list[Path]:
        found = {self.wiki}
        for path in self.wiki.rglob("*"):
            rel = path.relative_to(self.wiki)
            if path.is_dir() and not any(p.startswith(".") for p in rel.parts):
                found.add(path)
        return sorted(found)


def load_page(wiki: Wiki, path: Path) -> Page:
    text = path.read_text(encoding="utf-8", errors="replace")
    meta, body, body_line, errors = parse_frontmatter(text)
    return Page(
        path,
        path.relative_to(wiki.wiki).as_posix(),
        meta,
        body,
        text,
        body_line,
        errors,
    )


def slugify(text: str, limit: int = 60) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    if len(slug) > limit:
        cut = slug[:limit]
        slug = cut.rsplit("-", 1)[0] if "-" in cut else cut
    return slug or "untitled"


def split_tags(value: str | None) -> list[str]:
    return [t.strip() for t in (value or "").split(",") if t.strip()]


def validate_domain(domain: str) -> str:
    domain = domain.strip().strip("/")
    if not DOMAIN_RE.match(domain):
        raise WikiError(
            "domain-invalid",
            f"Domain '{domain}' is not valid. Use lowercase kebab-case segments, "
            "for example 'aws/iam' or 'machine-learning/transformers'.",
        )
    return domain


def code_free_lines(text: str) -> list[str]:
    """Lines of text with fenced blocks and inline code blanked out."""
    out: list[str] = []
    fence = ""
    for line in text.splitlines():
        marker = FENCE_RE.match(line)
        if fence:
            if marker and marker.group(1) == fence:
                fence = ""
            out.append("")
        elif marker:
            fence = marker.group(1)
            out.append("")
        else:
            out.append(INLINE_CODE_RE.sub(lambda m: " " * len(m.group(0)), line))
    return out


def page_links(page: Page) -> list[tuple[int, str]]:
    links: list[tuple[int, str]] = []
    for offset, line in enumerate(code_free_lines(page.body)):
        for match in LINK_RE.finditer(line):
            links.append((page.body_line + offset + 1, match.group(1)))
    return links


def resolve_link(page: Page, target: str) -> Path | None:
    """Resolve a relative link to an absolute path, or None for external links."""
    if re.match(r"^[a-zA-Z][a-zA-Z0-9+.-]*:", target) or target.startswith(("#", "/")):
        return None
    clean = urllib.parse.unquote(target.split("#", 1)[0].split("?", 1)[0])
    if not clean:
        return None
    return Path(os.path.normpath(page.path.parent / clean))


def inside(path: Path, parent: Path) -> bool:
    try:
        path.relative_to(parent)
        return True
    except ValueError:
        return False


# ---------------------------------------------------------------- index


def plural(kind: str) -> str:
    if kind.endswith("y") and kind[-2:-1] not in "aeiou":
        return kind[:-1].title() + "ies"
    if kind.endswith(("s", "x", "ch", "sh")):
        return kind.title() + "es"
    return kind.title() + "s"


def cell(text: str) -> str:
    return text.replace("\n", " ").replace("|", "\\|").strip()


def link_text(text: str) -> str:
    return cell(text).replace("[", "\\[").replace("]", "\\]")


def page_summary(page: Page) -> str:
    summary = page.get("summary")
    if not summary or PLACEHOLDER in summary:
        return "_summary pending_"
    return cell(summary)


def render_index(
    wiki: Wiki, directory: Path, dirs: list[Path], pages: list[Page]
) -> str:
    rel = directory.relative_to(wiki.wiki).as_posix()
    rel = "" if rel == "." else rel
    title = rel or "Wiki index"
    lines = [f"# {title}", "", INDEX_MARKER, ""]
    if not rel:
        lines += ["History: [log.md](log.md). Schema: [AGENTS.md](../AGENTS.md).", ""]
    children = [d for d in dirs if d.parent == directory]
    if children:
        lines += ["## Domains", "", "| Domain | Pages | Updated |", "|---|---|---|"]
        for child in children:
            below = [p for p in pages if inside(p.path, child)]
            latest = max((p.get("updated") for p in below), default="") or "—"
            lines.append(
                f"| [{child.name}]({child.name}/index.md) | {len(below)} | {latest} |"
            )
        lines.append("")
    here = [p for p in pages if p.path.parent == directory]
    known = wiki.kinds()
    groups: dict[str, list[Page]] = {}
    for page in here:
        kind = page.get("kind")
        groups.setdefault(kind if kind in known else "", []).append(page)
    for kind in known + [""]:
        members = sorted(groups.get(kind, []), key=lambda p: (p.title.lower(), p.rel))
        if not members:
            continue
        lines += [
            f"## {plural(kind) if kind else 'Other'}",
            "",
            "| Page | Summary | Tags | Updated | Sources |",
            "|---|---|---|---|---|",
        ]
        for page in members:
            lines.append(
                f"| [{link_text(page.title)}]({page.path.name}) | {page_summary(page)} | "
                f"{cell(', '.join(page.get_list('tags'))) or '—'} | "
                f"{cell(page.get('updated')) or '—'} | {len(page.get_list('sources'))} |"
            )
        lines.append("")
    if not children and not here:
        lines += ["_No pages yet._", ""]
    return "\n".join(lines).rstrip() + "\n"


def expected_indexes(wiki: Wiki) -> dict[Path, str]:
    pages = wiki.pages()
    dirs = set(wiki.dirs())
    for page in pages:
        parent = page.path.parent
        while inside(parent, wiki.wiki):
            dirs.add(parent)
            if parent == wiki.wiki:
                break
            parent = parent.parent
    ordered = sorted(dirs)
    return {d / "index.md": render_index(wiki, d, ordered, pages) for d in ordered}


def write_indexes(wiki: Wiki) -> list[str]:
    written: list[str] = []
    for path, content in expected_indexes(wiki).items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != content:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            written.append(path.relative_to(wiki.root).as_posix())
    return written



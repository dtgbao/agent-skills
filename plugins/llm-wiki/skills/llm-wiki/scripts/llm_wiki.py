def lint_wiki(wiki: Wiki) -> dict[str, Any]:
    errors: list[dict[str, Any]] = []
    warnings: list[dict[str, Any]] = []

    def add(
        bucket: list[dict[str, Any]], code: str, path: str, line: int, message: str
    ) -> None:
        bucket.append({"code": code, "path": path, "line": line, "message": message})

    pages = wiki.pages()
    kinds = wiki.kinds()
    by_path = {page.path: page for page in pages}
    inbound: dict[Path, set[Path]] = {page.path: set() for page in pages}
    referenced_raw: set[Path] = set()

    for page in pages:
        where = f"wiki/{page.rel}"
        if page.meta is None:
            add(
                errors,
                "frontmatter-missing",
                where,
                1,
                "Page has no frontmatter block.",
            )
        for problem in page.errors:
            add(errors, "frontmatter-invalid", where, 1, problem)
        if page.meta is not None:
            for key in REQUIRED_FIELDS:
                if not page.get(key):
                    add(
                        errors,
                        "field-missing",
                        where,
                        1,
                        f"Frontmatter field '{key}' is missing.",
                    )
            summary = page.get("summary")
            if len(summary) > SUMMARY_MAX:
                add(
                    errors,
                    "summary-too-long",
                    where,
                    1,
                    f"Summary has {len(summary)} characters; the limit is {SUMMARY_MAX}.",
                )
            if summary and re.search(r"\]\(|`|\*\*|<[a-z]", summary):
                add(
                    warnings,
                    "summary-markup",
                    where,
                    1,
                    "Write the summary as plain text.",
                )
            kind = page.get("kind")
            if kind and kind not in kinds:
                add(
                    errors,
                    "kind-unknown",
                    where,
                    1,
                    f"Kind '{kind}' is not known. Known: {', '.join(kinds)}. "
                    "Add domain kinds to the extra-kinds marker in AGENTS.md.",
                )
            domain = page.get("domain")
            if not page.directory:
                add(
                    errors,
                    "page-outside-domain",
                    where,
                    1,
                    "Move the page into a domain folder.",
                )
            elif domain and domain != page.directory:
                add(
                    errors,
                    "domain-mismatch",
                    where,
                    1,
                    f"Field domain is '{domain}' but the page is in '{page.directory}'.",
                )
            if domain and not DOMAIN_RE.match(domain):
                add(
                    errors,
                    "domain-invalid",
                    where,
                    1,
                    f"Domain '{domain}' is not kebab-case.",
                )
            for key in ("created", "updated", "retrieved"):
                value = page.get(key)
                if value and not DATE_RE.match(value):
                    add(
                        errors,
                        "date-invalid",
                        where,
                        1,
                        f"Field '{key}' must be YYYY-MM-DD.",
                    )
            created, updated = page.get("created"), page.get("updated")
            dated = (
                created
                and updated
                and DATE_RE.match(created)
                and DATE_RE.match(updated)
            )
            if dated and updated < created:
                add(
                    warnings,
                    "date-order",
                    where,
                    1,
                    "Field 'updated' is before 'created'.",
                )
            for source in page.get_list("sources"):
                if source.startswith("raw/"):
                    target = wiki.root / source
                    referenced_raw.add(Path(os.path.normpath(target)))
                    if not target.is_file():
                        add(
                            errors,
                            "source-missing",
                            where,
                            1,
                            f"Source '{source}' does not exist.",
                        )
        for offset, line in enumerate(code_free_lines(page.text)):
            if PLACEHOLDER in line:
                add(
                    errors,
                    "placeholder",
                    where,
                    offset + 1,
                    f"Placeholder remains: {line.strip()[:100]}",
                )
        for line, target in page_links(page):
            resolved = resolve_link(page, target)
            if resolved is None:
                continue
            if inside(resolved, wiki.raw):
                referenced_raw.add(resolved)
            if not inside(resolved, wiki.wiki):
                continue  # targets outside wiki/ (raw files, AGENTS.md) are not checked
            if not resolved.exists():
                add(
                    errors,
                    "link-broken",
                    where,
                    line,
                    f"Link target '{target}' does not exist.",
                )
            elif resolved in by_path and resolved != page.path:
                inbound[resolved].add(page.path)

    for page in pages:
        if (
            page.get("kind") != "overview"
            and page.meta is not None
            and not inbound[page.path]
        ):
            add(
                warnings,
                "orphan",
                f"wiki/{page.rel}",
                1,
                "No other page links here. Link it from a related page or an overview.",
            )

    entries, bad = read_log(wiki)
    if not wiki.log.is_file():
        add(
            errors,
            "log-missing",
            "wiki/log.md",
            1,
            "wiki/log.md does not exist. Run init.",
        )
    for line, text in bad:
        add(
            errors,
            "log-heading-invalid",
            "wiki/log.md",
            line,
            f"Heading must match '## [YYYY-MM-DD HH:MM] <op> | <title>': {text[:80]}",
        )
    previous = ""
    for entry in entries:
        if entry.op not in LOG_OPS:
            add(
                errors,
                "log-op-unknown",
                "wiki/log.md",
                entry.line,
                f"Unknown op '{entry.op}'.",
            )
        if previous and entry.when < previous:
            add(
                warnings,
                "log-order",
                "wiki/log.md",
                entry.line,
                "Entry is older than the one before.",
            )
        previous = entry.when
    ingests = [e for e in entries if e.op == "ingest"]
    for page in pages:
        if page.get("kind") != "source":
            continue
        rel = f"wiki/{page.rel}"
        if not any(rel in e.body or e.title == page.title for e in ingests):
            add(
                warnings,
                "ingest-log-missing",
                rel,
                1,
                f"No ingest log entry names this page. Run: llm_wiki.py log ingest "
                f'"{page.title}" --page {rel}',
            )

    if wiki.raw.is_dir():
        for path in sorted(wiki.raw.rglob("*")):
            rel_parts = path.relative_to(wiki.raw).parts
            if (
                not path.is_file()
                or any(p.startswith(".") for p in rel_parts)
                or "assets" in rel_parts
            ):
                continue
            if Path(os.path.normpath(path)) not in referenced_raw:
                add(
                    warnings,
                    "raw-unreferenced",
                    path.relative_to(wiki.root).as_posix(),
                    1,
                    "No page lists this raw file in 'sources' or links to it.",
                )

    for path, content in expected_indexes(wiki).items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != content:
            add(
                warnings,
                "index-stale",
                path.relative_to(wiki.root).as_posix(),
                1,
                "Index is missing or out of date. Run: llm_wiki.py index",
            )

    return {"errors": errors, "warnings": warnings, "pages": len(pages)}



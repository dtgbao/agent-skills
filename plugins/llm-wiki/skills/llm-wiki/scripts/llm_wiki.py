def cmd_setup(args: argparse.Namespace) -> tuple[dict[str, Any], str]:
    info = validate_remote(args.remote)
    root = resolve_root(args.root)
    branch = args.branch
    heads = remote_heads(root, args.remote)
    cloned = initialized = False
    empty = not root.exists() or (root.is_dir() and not any(root.iterdir()))
    if empty and heads:
        root.parent.mkdir(parents=True, exist_ok=True)
        clone_args = ["clone", "--origin", "origin"]
        if branch in heads:
            clone_args += ["--branch", branch]
        git(root, *clone_args, args.remote, str(root), cwd=root.parent)
        cloned = True
    elif not (root / ".git").exists():
        root.mkdir(parents=True, exist_ok=True)
        git(root, "init", "--quiet")
        git(root, "symbolic-ref", "HEAD", f"refs/heads/{branch}")
        git(root, "remote", "add", "origin", args.remote)
        initialized = True
    else:
        current = git(root, "remote", "get-url", "origin", check=False)
        if current.returncode != 0:
            git(root, "remote", "add", "origin", args.remote)
        elif current.stdout.strip() != args.remote:
            raise WikiError(
                "remote-mismatch",
                f"{root} already has origin {current.stdout.strip()}. "
                "Change it with git, or pass a different --root.",
            )
    config = load_config()
    config.update({"root": str(root), "remote": args.remote, "branch": branch})
    path = save_config(config)
    warnings = ["Use a private repository. Wiki pages can hold private notes."]
    if not info["github"]:
        warnings.append("The remote is not on github.com.")
    payload = {
        "ok": True,
        "root": str(root),
        "remote": args.remote,
        "branch": branch,
        "config_path": str(path),
        "cloned": cloned,
        "git_initialized": initialized,
        "wiki_exists": (root / "AGENTS.md").is_file(),
        "remote_branches": heads,
        "warnings": warnings,
    }
    nxt = "The wiki exists. Run: index" if payload["wiki_exists"] else "Next: init"
    text = (
        f"Setup done: {root} -> {args.remote} ({branch}). Config: {path}.\n{nxt}\n"
        + "\n".join(f"warning: {w}" for w in warnings)
    )
    return payload, text


def cmd_init(args: argparse.Namespace) -> tuple[dict[str, Any], str]:
    root = resolve_root(args.root)
    wiki = Wiki(root)
    created: list[str] = []
    skipped: list[str] = []

    def ensure_file(path: Path, content: str) -> None:
        rel = path.relative_to(root).as_posix()
        if path.exists():
            skipped.append(rel)
            return
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        created.append(rel)

    if args.preset and args.preset not in PRESETS:
        raise WikiError(
            "preset-unknown",
            f"Preset '{args.preset}' is unknown: {', '.join(PRESETS)}.",
        )
    extra, guide = PRESETS.get(args.preset or "", ([], ""))
    preset_text = (
        f"\nPreset `{args.preset}` adds these kinds:\n\n{guide}\n"
        if args.preset
        else ""
    )
    ensure_file(
        wiki.schema,
        SCHEMA_TEMPLATE.format(
            preset_text=preset_text,
            extra_kinds=", ".join(extra),
            summary_max=SUMMARY_MAX,
        ),
    )
    ensure_file(root / ".gitignore", ".DS_Store\n*.swp\n")
    ensure_file(wiki.raw / ".gitkeep", "")
    ensure_file(wiki.log, LOG_HEADER)
    for domain in args.domain or []:
        domain = validate_domain(domain)
        ensure_file(wiki.raw / domain / ".gitkeep", "")
        (wiki.wiki / domain).mkdir(parents=True, exist_ok=True)
    written = write_indexes(wiki)
    created += [w for w in written if w not in created]
    body = (
        "\n".join(f"- created: {c}" for c in created)
        or "- Nothing new; layout already exists."
    )
    heading = append_log(
        wiki, "bootstrap", f"Initialize wiki at {root.name}", body=body
    )
    payload = {
        "ok": True,
        "root": str(root),
        "created": created,
        "skipped": skipped,
        "log_heading": heading,
    }
    return (
        payload,
        f"Initialized {root}: {len(created)} created, {len(skipped)} kept.\n{heading}",
    )


def cmd_ingest(args: argparse.Namespace) -> tuple[dict[str, Any], str]:
    root = resolve_root(args.root)
    wiki = Wiki(root)
    wiki.require()
    domain = validate_domain(args.domain)
    kind = args.kind
    if kind not in wiki.kinds():
        raise WikiError(
            "kind-unknown", f"Kind '{kind}' is not known: {', '.join(wiki.kinds())}."
        )
    raw_dir = wiki.raw / domain
    planned: list[Planned] = []
    sources: list[str] = []
    source_url = ""
    title = args.title or ""
    source = args.source

    if is_url(source):
        source_url = source
        if args.snapshot:
            data, ctype = fetch(source)
            ext = url_extension(source, ctype)
            html_title, text = extract_html(data) if ext == ".html" else ("", "")
            title = title or html_title
            slug = slugify(
                args.name or url_slug_hint(source) or title or url_stem(source)
            )
            planned.append(plan_write(raw_dir / f"{slug}{ext}", data))
            if ext == ".html":
                derived = (
                    f"# {title or slug}\n\n"
                    f"Source: {source}\n"
                    f"Text extracted from {slug}.html by llm_wiki.py. "
                    "The .html file is the original.\n\n"
                    f"{text}\n"
                )
                planned.append(
                    plan_write(raw_dir / f"{slug}.md", derived.encode("utf-8"))
                )
        else:
            slug = slugify(
                args.name or url_slug_hint(source) or title or url_stem(source)
            )
            sources.append(source)
    else:
        if args.snapshot:
            raise WikiError(
                "snapshot-needs-url",
                "--snapshot works only with an http(s) or file URL.",
            )
        path = Path(source).expanduser().absolute()
        if not path.is_file():
            raise WikiError("source-missing", f"Source file {path} does not exist.")
        slug = slugify(args.name or title or path.stem)
        if inside(path.resolve(), wiki.raw.resolve()):
            sources.append(path.resolve().relative_to(wiki.root.resolve()).as_posix())
        else:
            planned.append(
                plan_write(raw_dir / f"{slug}{path.suffix.lower()}", path.read_bytes())
            )
    title = title or slug.replace("-", " ").capitalize()

    asset_plans: list[Planned] = []
    for asset in args.asset or []:
        if is_url(asset):
            data, ctype = fetch(asset)
            name = slugify(url_stem(asset)) + url_extension(asset, ctype)
        else:
            asset_path = Path(asset).expanduser()
            if not asset_path.is_file():
                raise WikiError("asset-missing", f"Asset {asset_path} does not exist.")
            data = asset_path.read_bytes()
            name = slugify(asset_path.stem) + asset_path.suffix.lower()
        asset_plans.append(plan_write(raw_dir / "assets" / slug / name, data))

    page_path = wiki.wiki / domain / f"{slug}.md"
    if page_path.exists():
        raise WikiError(
            "page-exists",
            f"{page_path.relative_to(root)} already exists. Update it instead, or pass --name.",
        )

    for plan in planned + asset_plans:
        if not plan.reused:
            plan.dest.parent.mkdir(parents=True, exist_ok=True)
            plan.dest.write_bytes(plan.data)
    sources = [p.dest.relative_to(root).as_posix() for p in planned] + sources

    meta: dict[str, str | list[str]] = {
        "title": title,
        "kind": kind,
        "domain": domain,
        "summary": SUMMARY_PLACEHOLDER,
        "tags": split_tags(args.tags),
        "sources": sources,
    }
    if source_url:
        meta["source_url"] = source_url
    if args.snapshot:
        meta["retrieved"] = today()
    meta["created"] = today()
    meta["updated"] = today()

    up = "../" * (len(domain.split("/")) + 1)
    source_lines = [
        f"- [{s}]({up}{s})" if s.startswith("raw/") else f"- <{s}>" for s in sources
    ] or ["- (none)"]
    asset_lines = [
        f"- ![{p.dest.stem}]({up}{p.dest.relative_to(root).as_posix()})"
        for p in asset_plans
    ]
    body = [
        f"# {title}",
        "",
        "## Source",
        "",
        *source_lines,
        "",
        "## Summary",
        "",
        f"{PLACEHOLDER}: 2-4 sentences in your own words.",
        "",
        "## Key takeaways",
        "",
        f"- {PLACEHOLDER}: takeaway, with the section or page of the source.",
        "",
        "## Entities and concepts",
        "",
        f"- {PLACEHOLDER}: link each one to its page, for example `[Name](name.md)`.",
        "",
        "## Contradictions and open questions",
        "",
        f"- {PLACEHOLDER}: conflicts with existing pages, or 'None found.'",
        "",
    ]
    if asset_lines:
        body += ["## Assets", "", *asset_lines, ""]
    page_path.parent.mkdir(parents=True, exist_ok=True)
    page_path.write_text(
        dump_frontmatter(meta) + "\n" + "\n".join(body), encoding="utf-8"
    )
    placeholders = page_path.read_text(encoding="utf-8").count(PLACEHOLDER)
    page_rel = page_path.relative_to(root).as_posix()
    payload = {
        "ok": True,
        "page": page_rel,
        "title": title,
        "domain": domain,
        "raw": [p.dest.relative_to(root).as_posix() for p in planned],
        "reused": [
            p.dest.relative_to(root).as_posix()
            for p in planned + asset_plans
            if p.reused
        ],
        "assets": [p.dest.relative_to(root).as_posix() for p in asset_plans],
        "sources": sources,
        "placeholders": placeholders,
    }
    lines = [f"Scaffold: {page_rel} ({placeholders} placeholders to replace)"]
    lines += [f"raw: {r}" for r in payload["raw"]] + [
        f"asset: {a}" for a in payload["assets"]
    ]
    lines.append(
        f'Next: write the pages, then index, lint, log ingest "{title}" --page {page_rel}'
    )
    return payload, "\n".join(lines)


def cmd_new(args: argparse.Namespace) -> tuple[dict[str, Any], str]:
    root = resolve_root(args.root)
    wiki = Wiki(root)
    wiki.require()
    kind = args.kind
    if kind == "source":
        raise WikiError(
            "kind-source",
            "Source pages come from ingest, which also stores the raw file. "
            "Run: llm_wiki.py ingest SRC --domain D",
        )
    if kind not in wiki.kinds():
        raise WikiError(
            "kind-unknown",
            f"Kind '{kind}' is not known: {', '.join(wiki.kinds())}. "
            "Add a new kind to the extra-kinds marker in AGENTS.md first.",
        )
    domain = validate_domain(args.domain)
    title = " ".join(args.title.split())
    if not title:
        raise WikiError("title-empty", "Pass --title with the page title.")
    path = wiki.wiki / domain / f"{slugify(args.name or title)}.md"
    rel = path.relative_to(root).as_posix()
    if path.exists():
        raise WikiError(
            "page-exists", f"{rel} already exists. Update it instead, or pass --name."
        )
    meta: dict[str, str | list[str]] = {
        "title": title,
        "kind": kind,
        "domain": domain,
        "summary": SUMMARY_PLACEHOLDER,
        "tags": split_tags(args.tags),
        "sources": args.source or [],
        "created": today(),
        "updated": today(),
    }
    sections = args.section or list(KIND_SECTIONS.get(kind, ("Notes",)))
    body = [f"# {title}", ""]
    for section in sections:
        body += [f"## {section}", "", f"{PLACEHOLDER}: write this section.", ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(dump_frontmatter(meta) + "\n" + "\n".join(body), encoding="utf-8")
    placeholders = path.read_text(encoding="utf-8").count(PLACEHOLDER)
    payload = {
        "ok": True,
        "page": rel,
        "title": title,
        "kind": kind,
        "domain": domain,
        "sections": sections,
        "placeholders": placeholders,
    }
    text = (
        f"Scaffold: {rel} ({placeholders} placeholders to replace)\n"
        "Next: write the page, link it from a related page, then index and lint."
    )
    return payload, text


def cmd_index(args: argparse.Namespace) -> tuple[dict[str, Any], str]:
    wiki = Wiki(resolve_root(args.root))
    wiki.require()
    written = write_indexes(wiki)
    pages = len(wiki.pages())
    text = f"Indexes: {len(written)} written, {pages} pages." + "".join(
        f"\n{w}" for w in written
    )
    return {"ok": True, "written": written, "pages": pages}, text


def cmd_search(args: argparse.Namespace) -> tuple[dict[str, Any], str]:
    wiki = Wiki(resolve_root(args.root))
    wiki.require()
    results = search_pages(wiki, args.query, args.limit, args.domain, args.kind)
    text = (
        "\n".join(
            f"{r['score']:7.3f}  {r['path']}  [{r['kind']}]  {r['summary']}"
            for r in results
        )
        or "No matches."
    )
    return {"ok": True, "query": args.query, "results": results}, text


def cmd_log(args: argparse.Namespace) -> tuple[dict[str, Any], str]:
    wiki = Wiki(resolve_root(args.root))
    wiki.require()
    body = sys.stdin.read() if args.body == "-" else (args.body or "")
    heading = append_log(
        wiki, args.op, args.title, args.page, body, args.follow_up, parse_when(args.at)
    )
    return {
        "ok": True,
        "path": wiki.log.relative_to(wiki.root).as_posix(),
        "heading": heading,
    }, heading


def cmd_lint(args: argparse.Namespace) -> tuple[dict[str, Any], str]:
    wiki = Wiki(resolve_root(args.root))
    wiki.require()
    report = lint_wiki(wiki)
    ok = not report["errors"] and not (args.strict and report["warnings"])
    lines = [
        f"E {e['code']} {e['path']}:{e['line']} {e['message']}"
        for e in report["errors"]
    ]
    lines += [
        f"W {w['code']} {w['path']}:{w['line']} {w['message']}"
        for w in report["warnings"]
    ]
    lines.append(
        f"{'OK' if ok else 'FAIL'}: {len(report['errors'])} errors, "
        f"{len(report['warnings'])} warnings, {report['pages']} pages."
    )
    payload = {"ok": ok, **report}
    if not ok:
        raise WikiError("lint-failed", "\n".join(lines), extra=payload)
    return payload, "\n".join(lines)


def cmd_sync(args: argparse.Namespace) -> tuple[dict[str, Any], str]:
    root = resolve_root(args.root)
    if not (root / ".git").exists():
        raise WikiError(
            "not-a-repo", f"{root} is not a Git repository. Run setup first."
        )
    gitdir = root / ".git"
    if (gitdir / "rebase-merge").exists() or (gitdir / "rebase-apply").exists():
        raise WikiError(
            "rebase-in-progress", "A rebase is in progress. Finish or abort it first."
        )
    if git(root, "remote", "get-url", "origin", check=False).returncode != 0:
        raise WikiError(
            "remote-missing", "The repository has no origin remote. Run setup."
        )
    head = git(root, "symbolic-ref", "--short", "HEAD", check=False)
    branch = head.stdout.strip() or load_config().get("branch") or DEFAULT_BRANCH
    git(root, "add", "-A")
    if (root / "AGENTS.md").is_file():
        # update-index bypasses ignore rules: a global ignore must not drop the schema.
        git(root, "update-index", "--add", "--", "AGENTS.md")
    committed = False
    if git(root, "diff", "--cached", "--quiet", check=False).returncode != 0:
        message = args.message or f"wiki: sync {now().strftime('%Y-%m-%d %H:%M')}"
        git(root, "commit", "--quiet", "-m", message)
        committed = True
    has_commit = git(root, "rev-parse", "--verify", "--quiet", "HEAD", check=False)
    commit = has_commit.stdout.strip() if has_commit.returncode == 0 else ""
    payload: dict[str, Any] = {
        "ok": True,
        "branch": branch,
        "committed": committed,
        "commit": commit,
        "pulled": False,
        "pushed": False,
        "conflicts": [],
        "resolved": [],
    }
    if not commit:
        return payload, "Nothing to sync: no commits and no changes."
    remote = git(root, "ls-remote", "--heads", "origin", branch, check=False)
    if remote.returncode != 0:
        raise WikiError(
            "remote-unreachable", f"Cannot reach origin: {remote.stderr.strip()}"
        )
    if remote.stdout.strip():
        pull = git(root, "pull", "--rebase", "--quiet", "origin", branch, check=False)
        while pull.returncode != 0:
            unmerged = git(root, "diff", "--name-only", "--diff-filter=U", check=False)
            conflicts = [line for line in unmerged.stdout.splitlines() if line.strip()]
            if resolve_generated(root, conflicts):
                payload["resolved"] += [
                    c for c in conflicts if c not in payload["resolved"]
                ]
                pull = git(root, "rebase", "--continue", check=False)
                continue
            git(root, "rebase", "--abort", check=False)
            payload.update({"ok": False, "conflicts": conflicts})
            raise WikiError(
                "rebase-conflict",
                "Pull --rebase hit conflicts. The rebase was aborted and the local commit "
                f"{commit[:10]} is kept. Conflicting files: {', '.join(conflicts) or 'unknown'}. "
                f"Details: {(pull.stderr or pull.stdout).strip()[:300]}",
                exit_code=2,
                extra=payload,
            )
        payload["pulled"] = True
        payload["commit"] = git(root, "rev-parse", "HEAD").stdout.strip()
    git(root, "push", "--quiet", "-u", "origin", f"HEAD:refs/heads/{branch}")
    payload["pushed"] = True
    text = (
        f"Synced {branch}: committed={committed}, pulled={payload['pulled']}, "
        f"pushed at {payload['commit'][:10]}."
    )
    if payload["resolved"]:
        text += f"\nAuto-resolved generated files: {', '.join(payload['resolved'])}."
    return payload, text


def resolve_generated(root: Path, conflicts: list[str]) -> bool:
    """Resolve a rebase stop when only log.md and index.md files conflict.

    log.md keeps the entries of both sides in time order. Indexes are regenerated
    from the merged pages. Return False, and change nothing in Git, otherwise.
    """
    wiki = Wiki(root)
    expected = {p.relative_to(root).as_posix() for p in expected_indexes(wiki)}
    if not conflicts or any(c != LOG_REL and c not in expected for c in conflicts):
        return False
    if LOG_REL in conflicts:
        ours = git(root, "show", f":2:{LOG_REL}", check=False)
        theirs = git(root, "show", f":3:{LOG_REL}", check=False)
        if ours.returncode or theirs.returncode:
            return False
        wiki.log.write_text(merge_logs(ours.stdout, theirs.stdout), encoding="utf-8")
    written = write_indexes(wiki)
    git(root, "add", "--", *dict.fromkeys(conflicts + written))
    return True


def cmd_status(args: argparse.Namespace) -> tuple[dict[str, Any], str]:
    root = resolve_root(args.root)
    wiki = Wiki(root)
    config = load_config()
    is_repo = (root / ".git").exists()
    remote = ""
    if is_repo:
        result = git(root, "remote", "get-url", "origin", check=False)
        remote = result.stdout.strip() if result.returncode == 0 else ""
    counts: dict[str, dict[str, int]] = {}
    recent: list[str] = []
    lint_counts = {"errors": 0, "warnings": 0}
    initialized = wiki.wiki.is_dir()
    if initialized:
        for page in wiki.pages():
            bucket = counts.setdefault(page.directory or "(root)", {})
            kind = page.get("kind") or "(none)"
            bucket[kind] = bucket.get(kind, 0) + 1
        entries, _ = read_log(wiki)
        recent = [f"[{e.when}] {e.op} | {e.title}" for e in entries[-5:]]
        report = lint_wiki(wiki)
        lint_counts = {
            "errors": len(report["errors"]),
            "warnings": len(report["warnings"]),
        }
    payload = {
        "ok": True,
        "root": str(root),
        "initialized": initialized,
        "git": is_repo,
        "remote": remote or config.get("remote", ""),
        "branch": config.get("branch", DEFAULT_BRANCH),
        "config_path": str(config_path()),
        "counts": counts,
        "recent_log": recent,
        "lint": lint_counts,
    }
    lines = [
        f"root: {root} ({'initialized' if initialized else 'not initialized'})",
        f"git: {is_repo}  remote: {payload['remote'] or '-'}",
    ]
    for domain, kinds in sorted(counts.items()):
        lines.append(
            f"{domain}: " + ", ".join(f"{k}={v}" for k, v in sorted(kinds.items()))
        )
    lines += recent
    lines.append(
        f"lint: {lint_counts['errors']} errors, {lint_counts['warnings']} warnings"
    )
    return payload, "\n".join(lines)



class WikiError(Exception):
    def __init__(
        self,
        code: str,
        message: str,
        exit_code: int = 1,
        extra: dict[str, Any] | None = None,
    ) -> None:
        super().__init__(message)
        self.code = code
        self.message = message
        self.exit_code = exit_code
        self.extra = extra or {}


# ---------------------------------------------------------------- config / root


def config_path() -> Path:
    return Path.home() / ".config" / "llm-wiki" / "config.json"


def load_config() -> dict[str, Any]:
    path = config_path()
    if not path.is_file():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise WikiError("config-invalid", f"Cannot read {path}: {exc}") from exc
    return data if isinstance(data, dict) else {}


def save_config(data: dict[str, Any]) -> Path:
    path = config_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    return path


def resolve_root(arg: str | None) -> Path:
    value = arg or os.environ.get("LLM_WIKI_ROOT") or load_config().get("root")
    root = Path(value) if value else Path.home() / ".llm-wiki"
    return root.expanduser().absolute()



def tokenize(text: str) -> list[str]:
    return [
        t for t in TOKEN_RE.findall(text.lower()) if len(t) > 1 and t not in STOPWORDS
    ]


def search_pages(
    wiki: Wiki,
    query: str,
    limit: int = 10,
    domain: str | None = None,
    kind: str | None = None,
) -> list[dict[str, Any]]:
    pages = wiki.pages()
    if domain:
        prefix = domain.strip("/")
        pages = [
            p
            for p in pages
            if p.directory == prefix or p.directory.startswith(prefix + "/")
        ]
    if kind:
        pages = [p for p in pages if p.get("kind") == kind]
    terms = list(dict.fromkeys(tokenize(query)))
    if not pages or not terms:
        return []
    docs: list[Counter[str]] = []
    for page in pages:
        tokens = (
            tokenize(page.title) * 3
            + tokenize(page.get("summary")) * 2
            + tokenize(" ".join(page.get_list("tags") + [page.get("domain")])) * 2
            + tokenize(page.body)
        )
        docs.append(Counter(tokens))
    lengths = [sum(doc.values()) for doc in docs]
    avg = (sum(lengths) / len(lengths)) or 1.0
    k1, b = 1.5, 0.75
    df = {t: sum(1 for doc in docs if t in doc) for t in terms}
    n = len(docs)
    results: list[dict[str, Any]] = []
    for page, doc, length in zip(pages, docs, lengths):
        score = 0.0
        for term in terms:
            tf = doc.get(term, 0)
            if not tf:
                continue
            idf = math.log(1 + (n - df[term] + 0.5) / (df[term] + 0.5))
            score += idf * tf * (k1 + 1) / (tf + k1 * (1 - b + b * length / avg))
        if score <= 0:
            continue
        snippet = next(
            (
                line.strip()
                for line in page.body.splitlines()
                if line.strip() and any(t in tokenize(line) for t in terms)
            ),
            "",
        )
        results.append(
            {
                "path": f"wiki/{page.rel}",
                "title": page.title,
                "kind": page.get("kind"),
                "domain": page.get("domain"),
                "summary": page.get("summary"),
                "score": round(score, 3),
                "snippet": snippet[:200],
            }
        )
    results.sort(key=lambda r: (-r["score"], r["path"]))
    return results[:limit]



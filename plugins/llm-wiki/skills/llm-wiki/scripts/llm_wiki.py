class TextExtractor(html.parser.HTMLParser):
    SKIP = frozenset({"script", "style", "noscript", "svg", "template", "head"})
    BLOCK = frozenset(
        [
            "address",
            "article",
            "aside",
            "blockquote",
            "br",
            "dd",
            "div",
            "dl",
            "dt",
            "figcaption",
            "figure",
            "footer",
            "form",
            "header",
            "hr",
            "main",
            "nav",
            "ol",
            "p",
            "pre",
            "section",
            "table",
            "tr",
            "ul",
        ]
    )

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.parts: list[str] = []
        self.skip = 0
        self.in_title = False
        self.title = ""

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        if tag == "title":
            self.in_title = True
        if tag in self.SKIP:
            self.skip += 1
        elif re.fullmatch(r"h[1-6]", tag):
            self.parts.append("\n\n" + "#" * int(tag[1]) + " ")
        elif tag == "li":
            self.parts.append("\n- ")
        elif tag in self.BLOCK:
            self.parts.append("\n\n")

    def handle_endtag(self, tag: str) -> None:
        if tag == "title":
            self.in_title = False
        if tag in self.SKIP:
            self.skip = max(0, self.skip - 1)
        elif tag in self.BLOCK or re.fullmatch(r"h[1-6]", tag):
            self.parts.append("\n\n")

    def handle_data(self, data: str) -> None:
        if self.in_title:
            self.title += data
        if not self.skip:
            self.parts.append(re.sub(r"\s+", " ", data))

    def text(self) -> str:
        joined = "".join(self.parts)
        lines = [line.strip() for line in joined.splitlines()]
        return re.sub(r"\n{3,}", "\n\n", "\n".join(lines)).strip()


def extract_html(data: bytes) -> tuple[str, str]:
    parser = TextExtractor()
    parser.feed(data.decode("utf-8", errors="replace"))
    parser.close()
    return " ".join(parser.title.split()), parser.text()


EXTENSIONS = {
    "text/html": ".html",
    "application/xhtml+xml": ".html",
    "text/markdown": ".md",
    "text/x-markdown": ".md",
    "text/plain": ".txt",
    "application/pdf": ".pdf",
    "application/json": ".json",
    "image/png": ".png",
    "image/jpeg": ".jpg",
    "image/gif": ".gif",
    "image/webp": ".webp",
    "image/svg+xml": ".svg",
}


def fetch(url: str) -> tuple[bytes, str]:
    request = urllib.request.Request(url, headers={"User-Agent": f"llm-wiki/{VERSION}"})
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            data = response.read()
            ctype = (
                (response.headers.get("Content-Type") or "")
                .split(";")[0]
                .strip()
                .lower()
            )
    except (OSError, ValueError) as exc:
        raise WikiError("fetch-failed", f"Cannot fetch {url}: {exc}") from exc
    return data, ctype


def url_extension(url: str, ctype: str) -> str:
    suffix = Path(urllib.parse.urlsplit(url).path).suffix.lower()
    if ctype in EXTENSIONS:
        return EXTENSIONS[ctype]
    if re.fullmatch(r"\.[a-z0-9]{1,5}", suffix):
        return ".html" if suffix == ".htm" else suffix
    return ".bin"


GENERIC_STEMS = frozenset(
    {"index", "default", "article", "post", "page", "view", "read"}
)


def url_stem(url: str) -> str:
    parts = urllib.parse.urlsplit(url)
    stem = Path(parts.path).stem if parts.path.strip("/") else ""
    return stem or parts.netloc or "source"


def url_slug_hint(url: str) -> str:
    """A descriptive URL path stem, or '' when the path says nothing useful."""
    stem = Path(urllib.parse.urlsplit(url).path).stem
    words = re.findall(r"[a-z]+", stem.lower())
    return stem if len(words) >= 2 and stem.lower() not in GENERIC_STEMS else ""


@dataclass
class Planned:
    dest: Path
    data: bytes
    reused: bool = False


def plan_write(dest: Path, data: bytes) -> Planned:
    """Plan a raw write. Identical bytes are reused; different bytes are refused."""
    if dest.exists():
        if dest.is_file() and dest.read_bytes() == data:
            return Planned(dest, data, reused=True)
        raise WikiError(
            "name-collision",
            f"{dest} already exists with different content. Raw files are immutable. "
            "Pass --name with a new slug.",
        )
    return Planned(dest, data)


def is_url(value: str) -> bool:
    return bool(re.match(r"^(https?|file)://", value, re.IGNORECASE))


# ---------------------------------------------------------------- git


def git(
    root: Path, *args: str, check: bool = True, cwd: Path | None = None
) -> subprocess.CompletedProcess[str]:
    env = dict(os.environ, GIT_TERMINAL_PROMPT="0", GIT_EDITOR="true")
    try:
        result = subprocess.run(
            ["git", *args],
            cwd=str(cwd or root),
            capture_output=True,
            text=True,
            env=env,
            check=False,
        )
    except FileNotFoundError as exc:
        raise WikiError("git-missing", "git is not installed or not on PATH.") from exc
    if check and result.returncode != 0:
        detail = (result.stderr or result.stdout).strip()
        raise WikiError("git-failed", f"git {' '.join(args)} failed: {detail}")
    return result


def validate_remote(url: str) -> dict[str, Any]:
    url = url.strip()
    if not url:
        raise WikiError(
            "remote-missing", "Pass --remote with an existing repository URL."
        )
    if GITHUB_TOKEN_RE.search(url):
        raise WikiError(
            "credentials-in-url", "The remote URL contains a GitHub token. Remove it."
        )
    scp = re.match(r"^([A-Za-z0-9._-]+)@([A-Za-z0-9.-]+):(?!//)(.+)$", url)
    if scp:
        return {
            "kind": "ssh",
            "host": scp.group(2),
            "github": scp.group(2) == "github.com",
        }
    parts = urllib.parse.urlsplit(url)
    scheme = parts.scheme.lower()
    if scheme in ("http", "https", "ssh", "git"):
        if parts.password is not None or (
            scheme in ("http", "https") and parts.username
        ):
            raise WikiError(
                "credentials-in-url",
                "The remote URL contains credentials (user:token@). Use a clean URL and "
                "authenticate with SSH keys, `gh auth login` or a Git credential helper.",
            )
        if scheme in ("http", "https") and (parts.query or parts.fragment):
            raise WikiError(
                "credentials-in-url", "The remote URL must not have a query string."
            )
        host = parts.hostname or ""
        return {"kind": scheme, "host": host, "github": host == "github.com"}
    if scheme == "file" or scheme == "" or len(scheme) == 1:
        local = Path(
            urllib.parse.unquote(parts.path) if scheme == "file" else url
        ).expanduser()
        if not local.exists():
            raise WikiError(
                "remote-unreachable", f"Local repository {local} does not exist."
            )
        return {"kind": "local", "host": "", "github": False}
    raise WikiError("remote-unsupported", f"Remote scheme '{scheme}' is not supported.")


def remote_heads(root: Path, remote: str) -> list[str]:
    result = git(root, "ls-remote", "--heads", remote, check=False, cwd=Path.home())
    if result.returncode != 0:
        raise WikiError(
            "remote-unreachable",
            f"Cannot reach {remote}: {(result.stderr or '').strip()} "
            "Create the repository first (private is recommended), for example: "
            "gh repo create <name> --private",
        )
    return [
        line.split("refs/heads/", 1)[1]
        for line in result.stdout.splitlines()
        if "refs/heads/" in line
    ]



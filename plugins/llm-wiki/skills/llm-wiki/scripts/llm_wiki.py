def build_parser() -> argparse.ArgumentParser:
    # --root and --json work before or after the command. Subcommand defaults are
    # suppressed so that they never overwrite a value given before the command.
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument(
        "--root",
        default=argparse.SUPPRESS,
        help="wiki root (default: config, then ~/.llm-wiki)",
    )
    common.add_argument(
        "--json",
        action="store_true",
        default=argparse.SUPPRESS,
        help="print machine-readable JSON",
    )
    parser = argparse.ArgumentParser(
        prog="llm_wiki.py", description="Mechanical steps for an LLM-maintained wiki."
    )
    parser.add_argument("--root", default=None, help=argparse.SUPPRESS)
    parser.add_argument("--json", action="store_true", help=argparse.SUPPRESS)
    parser.add_argument("--version", action="version", version=f"llm-wiki {VERSION}")
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser(
        "setup", parents=[common], help="connect a wiki root to a Git remote"
    )
    p.add_argument(
        "--remote", required=True, help="existing repository URL (private recommended)"
    )
    p.add_argument("--branch", default=DEFAULT_BRANCH)
    p.set_defaults(func=cmd_setup)

    p = sub.add_parser(
        "init", parents=[common], help="create the layout; logs a bootstrap event"
    )
    p.add_argument("--preset", help=f"add domain page kinds: {', '.join(PRESETS)}")
    p.add_argument(
        "--domain", action="append", help="create a domain folder (repeatable)"
    )
    p.set_defaults(func=cmd_init)

    p = sub.add_parser(
        "ingest", parents=[common], help="copy or snapshot a source; scaffold its page"
    )
    p.add_argument("source", help="local file path or URL")
    p.add_argument(
        "--domain", required=True, help="primary domain, for example aws/iam"
    )
    p.add_argument("--title")
    p.add_argument("--name", help="slug for raw file and page (default: from title)")
    p.add_argument("--kind", default="source")
    p.add_argument("--tags", help="comma-separated tags")
    p.add_argument(
        "--snapshot", action="store_true", help="save the URL content into raw/"
    )
    p.add_argument(
        "--asset", action="append", help="image or file to copy into raw assets"
    )
    p.set_defaults(func=cmd_ingest)

    p = sub.add_parser(
        "new", parents=[common], help="scaffold a non-source page; writes no log entry"
    )
    p.add_argument("kind", help="page kind, for example entity, concept or decision")
    p.add_argument("--domain", required=True, help="domain, for example aws/iam")
    p.add_argument("--title", required=True)
    p.add_argument("--name", help="slug for the file name (default: from title)")
    p.add_argument("--tags", help="comma-separated tags")
    p.add_argument(
        "--source", action="append", help="raw path or URL for sources: (repeatable)"
    )
    p.add_argument(
        "--section",
        action="append",
        help="body section; replaces the kind's default sections (repeatable)",
    )
    p.set_defaults(func=cmd_new)

    p = sub.add_parser(
        "index", parents=[common], help="rebuild every index.md; writes no log entry"
    )
    p.set_defaults(func=cmd_index)

    p = sub.add_parser("search", parents=[common], help="BM25 search over wiki pages")
    p.add_argument("query")
    p.add_argument("--limit", type=int, default=10)
    p.add_argument("--domain")
    p.add_argument("--kind")
    p.set_defaults(func=cmd_search)

    p = sub.add_parser("log", parents=[common], help="append an entry to wiki/log.md")
    p.add_argument("op", choices=LOG_OPS)
    p.add_argument("title")
    p.add_argument("--page", action="append", help="page path touched (repeatable)")
    p.add_argument("--body", help="entry text, or '-' to read stdin")
    p.add_argument("--follow-up", action="append", help="follow-up item (repeatable)")
    p.add_argument("--at", help="timestamp 'YYYY-MM-DD HH:MM' (default: now)")
    p.set_defaults(func=cmd_log)

    p = sub.add_parser("lint", parents=[common], help="mechanical health checks")
    p.add_argument("--strict", action="store_true", help="warnings also fail")
    p.set_defaults(func=cmd_lint)

    p = sub.add_parser(
        "sync", parents=[common], help="commit, pull --rebase, push (no force)"
    )
    p.add_argument("--message", "-m")
    p.set_defaults(func=cmd_sync)

    p = sub.add_parser(
        "status", parents=[common], help="root, remote, counts, recent log, lint"
    )
    p.set_defaults(func=cmd_status)
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        payload, text = args.func(args)
    except WikiError as exc:
        error = {
            "ok": False,
            **exc.extra,
            "error": {"code": exc.code, "message": exc.message},
        }
        if args.json:
            print(json.dumps(error, indent=2, ensure_ascii=False))
        elif exc.code == "lint-failed":
            print(exc.message)
        else:
            print(f"error [{exc.code}]: {exc.message}", file=sys.stderr)
        return exc.exit_code
    if args.json:
        print(json.dumps(payload, indent=2, ensure_ascii=False))
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())

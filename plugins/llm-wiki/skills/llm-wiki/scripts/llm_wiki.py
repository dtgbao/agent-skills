@dataclass
class LogEntry:
    line: int
    when: str
    op: str
    title: str
    body: str


def read_log(wiki: Wiki) -> tuple[list[LogEntry], list[tuple[int, str]]]:
    """Return parsed entries and (line, text) of malformed '## ' headings."""
    if not wiki.log.is_file():
        return [], []
    entries: list[LogEntry] = []
    bad: list[tuple[int, str]] = []
    body: list[str] = []
    for number, line in enumerate(wiki.log.read_text(encoding="utf-8").splitlines(), 1):
        if line.startswith("## "):
            if entries:
                entries[-1].body = "\n".join(body)
            body = []
            match = LOG_HEADING_RE.match(line)
            if match:
                entries.append(
                    LogEntry(number, match.group(1), match.group(2), match.group(3), "")
                )
            else:
                bad.append((number, line))
        else:
            body.append(line)
    if entries:
        entries[-1].body = "\n".join(body)
    return entries, bad


def append_log(
    wiki: Wiki,
    op: str,
    title: str,
    pages: list[str] | None = None,
    body: str = "",
    follow_ups: list[str] | None = None,
    when: dt.datetime | None = None,
) -> str:
    if op not in LOG_OPS:
        raise WikiError(
            "log-op-invalid", f"Op '{op}' is not one of: {', '.join(LOG_OPS)}."
        )
    title = " ".join(title.split())
    if not title:
        raise WikiError("log-title-empty", "The log entry needs a title.")
    heading = f"## [{(when or now()).strftime('%Y-%m-%d %H:%M')}] {op} | {title}"
    parts: list[str] = [heading, ""]
    for page in pages or []:
        parts.append(f"- page: {page}")
    if pages:
        parts.append("")
    if body.strip():
        demoted = re.sub(r"(?m)^#{1,2} ", "### ", body.strip())
        parts += [demoted, ""]
    if follow_ups:
        parts += (
            ["### Follow-ups", ""] + [f"- {item.strip()}" for item in follow_ups] + [""]
        )
    wiki.log.parent.mkdir(parents=True, exist_ok=True)
    existing = (
        wiki.log.read_text(encoding="utf-8") if wiki.log.is_file() else LOG_HEADER
    )
    existing = existing.rstrip("\n") + "\n\n"
    wiki.log.write_text(
        existing + "\n".join(parts).rstrip("\n") + "\n", encoding="utf-8"
    )
    return heading


def parse_when(value: str | None) -> dt.datetime | None:
    if not value:
        return None
    try:
        return dt.datetime.strptime(value, "%Y-%m-%d %H:%M")
    except ValueError as exc:
        raise WikiError("time-invalid", "Use --at 'YYYY-MM-DD HH:MM'.") from exc


def split_log(text: str) -> tuple[str, list[tuple[str, str]]]:
    """Return the preamble and (timestamp, block) pairs, one block per '## ' entry."""
    head: list[str] = []
    blocks: list[tuple[str, list[str]]] = []
    for line in text.splitlines():
        if line.startswith("## "):
            match = LOG_HEADING_RE.match(line)
            blocks.append((match.group(1) if match else "", [line]))
        elif blocks:
            blocks[-1][1].append(line)
        else:
            head.append(line)
    return "\n".join(head), [(when, "\n".join(lines).strip()) for when, lines in blocks]


def merge_logs(ours: str, theirs: str) -> str:
    """Keep every entry of both sides once. Entries only in theirs go in time order."""
    head, merged = split_log(ours)
    seen = {block for _, block in merged}
    for when, block in split_log(theirs)[1]:
        if block in seen:
            continue
        seen.add(block)
        at = len(merged)
        while at and when and merged[at - 1][0] > when:
            at -= 1
        merged.insert(at, (when, block))
    entries = "\n\n".join(block for _, block in merged)
    return head.rstrip("\n") + ("\n\n" + entries if entries else "") + "\n"


